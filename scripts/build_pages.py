#!/usr/bin/env python3
"""Give every page of the site its own real URL.

index.html is the one file to edit. This script reads it plus routes.json and writes:

  * the <head> metadata block (title, description, canonical, social cards, structured data)
    for each page, between the page-meta markers
  * a copy of the site at each page's path, e.g. become-a-surrogate/index.html, with that
    page shown first, so search engines and shared links see the right page
  * 404.html, sitemap.xml and robots.txt

Run it after every change to index.html or routes.json:

    python3 scripts/build_pages.py          # write the files
    python3 scripts/build_pages.py --check  # fail if any file is out of date (used by CI)
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START, END = '<!-- page-meta:start -->', '<!-- page-meta:end -->'


def strip_tags(fragment):
    text = re.sub(r'<[^>]+>', ' ', fragment)
    return re.sub(r'\s+', ' ', html.unescape(text)).strip()


def page_section(doc, name):
    m = re.search(r'<main class="page[^"]*" data-page="%s">(.*?)</main>' % re.escape(name), doc, re.S)
    return m.group(1) if m else ''


def faq_schema(doc, name):
    """FAQPage structured data built from the <details> questions on a page."""
    items = []
    for q, a in re.findall(r'<details>\s*<summary>(.*?)</summary>(.*?)</details>', page_section(doc, name), re.S):
        items.append({'@type': 'Question', 'name': strip_tags(q),
                      'acceptedAnswer': {'@type': 'Answer', 'text': strip_tags(a)}})
    return {'@context': 'https://schema.org', '@type': 'FAQPage', 'mainEntity': items} if items else None


def head_block(cfg, name, doc, not_found=False):
    site = cfg['site']
    r = cfg['routes'][name]
    url = site + r['path']
    image = site + r.get('image', cfg['defaultImage'])
    e = lambda v: html.escape(v, quote=True)
    lines = [
        START,
        '<!-- Generated by scripts/build_pages.py from routes.json. Edit those, not this block. -->',
        '<title>%s</title>' % e(r['title']),
        '<meta name="description" content="%s">' % e(r['description']),
    ]
    if not_found:
        lines.append('<meta name="robots" content="noindex">')
    else:
        lines.append('<link rel="canonical" href="%s">' % e(url))
    lines += [
        '<meta property="og:type" content="website">',
        '<meta property="og:site_name" content="Ember Surrogacy">',
        '<meta property="og:url" content="%s">' % e(url),
        '<meta property="og:title" content="%s">' % e(r['title']),
        '<meta property="og:description" content="%s">' % e(r['description']),
        '<meta property="og:image" content="%s">' % e(image),
        '<meta name="twitter:card" content="summary_large_image">',
        '<meta name="twitter:title" content="%s">' % e(r['title']),
        '<meta name="twitter:description" content="%s">' % e(r['description']),
        '<meta name="twitter:image" content="%s">' % e(image),
    ]
    routes = {k: {f: v[f] for f in ('path', 'title', 'description', 'legacyAnchors') if f in v}
              for k, v in cfg['routes'].items()}
    lines.append('<script>window.EMBER_SITE = %s; window.EMBER_ROUTES = %s;</script>'
                 % (json.dumps(site), json.dumps(routes, separators=(',', ':'))))
    schemas = []
    if name == 'home' and not not_found:
        schemas.append({
            '@context': 'https://schema.org', '@type': 'Organization', 'name': 'Ember Surrogacy',
            'legalName': 'Ember Families LLC', 'url': site + '/', 'logo': site + '/favicon-512x512.png',
            'email': 'info@embersurrogacy.com',
            'address': {'@type': 'PostalAddress', 'streetAddress': '1 Fair Oaks St.', 'addressLocality': 'San Francisco',
                        'addressRegion': 'CA', 'postalCode': '94110', 'addressCountry': 'US'},
            'sameAs': ['https://www.instagram.com/embersurrogacy/', 'https://www.linkedin.com/company/ember-surrogacy'],
        })
    elif not not_found:
        schemas.append({
            '@context': 'https://schema.org', '@type': 'BreadcrumbList', 'itemListElement': [
                {'@type': 'ListItem', 'position': 1, 'name': 'Home', 'item': site + '/'},
                {'@type': 'ListItem', 'position': 2, 'name': r['title'].split(' | ')[0], 'item': url},
            ]})
        faq = faq_schema(doc, name)
        if faq:
            schemas.append(faq)
    for s in schemas:
        lines.append('<script type="application/ld+json">%s</script>'
                     % json.dumps(s, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/'))
    lines.append(END)
    return '\n'.join(lines)


def render(doc, cfg, name, not_found=False):
    a, b = doc.index(START), doc.index(END) + len(END)
    out = doc[:a] + head_block(cfg, name, doc, not_found) + doc[b:]
    # Show this page without waiting for JavaScript.
    out = re.sub(r'<main class="page(?: active)?" data-page="([^"]+)">',
                 lambda m: '<main class="page%s" data-page="%s">' % (' active' if m.group(1) == name else '', m.group(1)),
                 out)
    return out


def build():
    cfg = json.loads((ROOT / 'routes.json').read_text())
    doc = (ROOT / 'index.html').read_text()
    files = {}
    for name, r in cfg['routes'].items():
        rel = r['path'].strip('/')
        files[(rel + '/index.html') if rel else 'index.html'] = render(doc, cfg, name)
    files['404.html'] = render(doc, cfg, 'home', not_found=True)
    files['sitemap.xml'] = ('<?xml version="1.0" encoding="UTF-8"?>\n'
                            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
                            + ''.join('  <url><loc>%s%s</loc></url>\n' % (cfg['site'], r['path'])
                                      for r in cfg['routes'].values())
                            + '</urlset>\n')
    files['robots.txt'] = 'User-agent: *\nAllow: /\n\nSitemap: %s/sitemap.xml\n' % cfg['site']
    return files


def main():
    check = '--check' in sys.argv
    stale = []
    for rel, content in build().items():
        path = ROOT / rel
        if path.exists() and path.read_text() == content:
            continue
        stale.append(rel)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if check and stale:
        print('Out of date: %s\nRun: python3 scripts/build_pages.py' % ', '.join(stale))
        sys.exit(1)
    print(('Up to date.' if check else 'Wrote: %s' % (', '.join(stale) or 'nothing, all up to date')))


if __name__ == '__main__':
    main()
